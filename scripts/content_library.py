def cover_svg(topic: Topic) -> str:
    cat = CATEGORIES[topic.category]
    accent, tint = cat["accent"], cat["tint"]
    seed = int(hashlib.sha256(topic.slug.encode()).hexdigest(), 16)
    rnd = lambda n, k=0: (seed >> (k * 7)) % n
    label = escape(topic.cover)
    size = 92 if len(topic.cover) <= 10 else 78 if len(topic.cover) <= 14 else 64
    motif = cat["motif"]
    shapes = []
    ox, oy = 700 + rnd(60, 1), 150 + rnd(60, 2)
    if motif == "document":
        for k in range(3):
            x, y = ox + k * 34, oy + k * 30
            shapes.append(f'<path d="M{x} {y}h250l60 60v330h-310z" fill="#fff" stroke="{accent}" stroke-width="5" opacity="{0.45 + k * 0.27:.2f}"/>')
        x, y = ox + 68, oy + 60
        shapes.append(f'<path d="M{x + 250} {y}v60h60" fill="none" stroke="{accent}" stroke-width="5"/>')
        for r in range(6):
            w = 200 - (r * 37 + rnd(40, r + 3)) % 120
            shapes.append(f'<rect x="{x + 34}" y="{y + 110 + r * 38}" width="{w + 40}" height="12" rx="6" fill="{accent}" opacity=".28"/>')
    elif motif == "image":
        shapes.append(f'<rect x="{ox}" y="{oy}" width="380" height="300" rx="18" fill="#fff" stroke="{accent}" stroke-width="6"/>')
        shapes.append(f'<circle cx="{ox + 290}" cy="{oy + 80}" r="34" fill="{accent}" opacity=".35"/>')
        shapes.append(f'<path d="M{ox + 20} {oy + 270}l110-130 80 90 50-50 100 90z" fill="{accent}" opacity=".55"/>')
        for k in range(5):
            shapes.append(f'<rect x="{ox + 400 + (k % 2) * 34}" y="{oy + 40 + k * 46}" width="26" height="26" fill="{accent}" opacity="{0.2 + (k * 0.13) % 0.6:.2f}"/>')
    elif motif == "nodes":
        cx, cy, ring = ox + 200, oy + 210, 150 + rnd(30, 1)
        count = 6 + rnd(3, 2)
        start = rnd(360, 3)
        pts = []
        for k in range(count):
            ang = math.radians(start + k * 360 / count)
            rr = ring - (k % 2) * 40
            pts.append((cx + rr * math.cos(ang), cy + rr * math.sin(ang)))
        for k, (x, y) in enumerate(pts):
            nx, ny = pts[(k + 1) % count]
            shapes.append(f'<line x1="{x:.0f}" y1="{y:.0f}" x2="{nx:.0f}" y2="{ny:.0f}" stroke="{accent}" stroke-width="3" opacity=".25"/>')
            shapes.append(f'<line x1="{cx}" y1="{cy}" x2="{x:.0f}" y2="{y:.0f}" stroke="{accent}" stroke-width="4" opacity=".45"/>')
        for k, (x, y) in enumerate(pts):
            shapes.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{18 + (k % 3) * 6}" fill="#fff" stroke="{accent}" stroke-width="5"/>')
        shapes.append(f'<circle cx="{cx}" cy="{cy}" r="46" fill="{accent}"/><circle cx="{cx}" cy="{cy}" r="18" fill="#fff" opacity=".9"/>')
    elif motif == "wave":
        for k in range(18):
            h = 40 + (rnd(9, k) * 31 + k * 17) % 230
            shapes.append(f'<rect x="{ox + k * 24}" y="{oy + 200 - h / 2:.0f}" width="12" height="{h}" rx="6" fill="{accent}" opacity="{0.35 + (k % 3) * 0.2:.2f}"/>')
        shapes.append(f'<circle cx="{ox + 210}" cy="{oy + 200}" r="62" fill="#fff" stroke="{accent}" stroke-width="6"/>')
        shapes.append(f'<path d="M{ox + 192} {oy + 168}l50 32-50 32z" fill="{accent}"/>')
    elif motif == "qr":
        cell = 26
        for (fx, fy) in ((0, 0), (8, 0), (0, 8)):
            x, y = ox + fx * cell, oy + fy * cell
            shapes.append(f'<rect x="{x}" y="{y}" width="{cell * 5}" height="{cell * 5}" fill="none" stroke="{accent}" stroke-width="{cell * 0.8:.0f}"/>')
            shapes.append(f'<rect x="{x + cell * 1.5}" y="{y + cell * 1.5}" width="{cell * 2}" height="{cell * 2}" fill="{accent}"/>')
        for k in range(46):
            cx, cy = (seed >> k) % 13, (seed >> (k + 3)) % 13
            if (cx < 6 and cy < 6) or (cx > 7 and cy < 6) or (cx < 6 and cy > 7):
                continue
            shapes.append(f'<rect x="{ox + cx * cell - 13}" y="{oy + cy * cell - 13}" width="{cell}" height="{cell}" fill="{accent}" opacity=".75"/>')
    else:  # checklist
        for r in range(4):
            y = oy + r * 82
            done = r < 2 + rnd(2, r)
            shapes.append(f'<rect x="{ox}" y="{y}" width="52" height="52" rx="10" fill="#fff" stroke="{accent}" stroke-width="5"/>')
            if done:
                shapes.append(f'<path d="M{ox + 12} {y + 27}l11 11 19-22" fill="none" stroke="{accent}" stroke-width="6" stroke-linecap="round" stroke-linejoin="round"/>')
            shapes.append(f'<rect x="{ox + 80}" y="{y + 18}" width="{220 + rnd(90, r + 4)}" height="16" rx="8" fill="{accent}" opacity="{0.55 if done else 0.25}"/>')
    grid = "".join(f'<circle cx="{60 + x * 40}" cy="{60 + y * 40}" r="2" fill="{accent}" opacity=".16"/>' for x in range(14) for y in range(16))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 750" width="1200" height="750" role="img" aria-label="{label}">'
            f'<rect width="1200" height="750" fill="{tint}"/>{grid}'
            f'<rect x="0" y="0" width="12" height="750" fill="{accent}"/>'
            f'{"".join(shapes)}'
            f'<text x="80" y="610" font-family="Inter,Segoe UI,Arial,Helvetica,sans-serif" font-size="{size}" font-weight="800" letter-spacing="-2" fill="#0c1a2d">{label}</text>'
            f'<rect x="80" y="650" width="120" height="10" rx="5" fill="{accent}"/>'
            f'</svg>\n')


