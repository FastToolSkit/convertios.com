def pagination(lang, base_rel, current, total):
    if total <= 1:
        return ""
    t = L10N[lang]
    rtl = lang == "ar"
    prev_arrow, next_arrow = ("→", "←") if rtl else ("←", "→")
    href = lambda n: local(lang, base_rel if n == 1 else f"{base_rel}page/{n}/")
    parts = []
    if current > 1:
        parts.append(f'<a class="lib-page lib-page--step" rel="prev" href="{href(current - 1)}"><span aria-hidden="true">{prev_arrow}</span> {t["prev"]}</a>')
    else:
        parts.append(f'<span class="lib-page lib-page--step" aria-disabled="true"><span aria-hidden="true">{prev_arrow}</span> {t["prev"]}</span>')
    numbers = []
    shown = set(range(1, total + 1)) if total <= 7 else {1, 2, total - 1, total, current - 1, current, current + 1}
    previous_shown = 0
    for n in range(1, total + 1):
        if n not in shown:
            continue
        if n - previous_shown > 1:
            numbers.append('<li class="lib-pages__gap" aria-hidden="true">…</li>')
        previous_shown = n
        if n == current:
            numbers.append(f'<li><a class="lib-page lib-page--num" href="{href(n)}" aria-current="page" aria-label="{t["page"]} {n} {t["of"]} {total}">{n}</a></li>')
        else:
            numbers.append(f'<li><a class="lib-page lib-page--num" href="{href(n)}" aria-label="{t["page"]} {n} {t["of"]} {total}">{n}</a></li>')
    parts.append(f'<ol class="lib-pages">{"".join(numbers)}</ol>')
    if current < total:
        parts.append(f'<a class="lib-page lib-page--step" rel="next" href="{href(current + 1)}">{t["next"]} <span aria-hidden="true">{next_arrow}</span></a>')
    else:
        parts.append(f'<span class="lib-page lib-page--step" aria-disabled="true">{t["next"]} <span aria-hidden="true">{next_arrow}</span></span>')
    return f'<nav class="lib-pagination" aria-label="{t["pagination"]}">{"".join(parts)}</nav>'


