def shell(lang: str) -> str:
    path = TEMPLATES / f"{lang}.html"
    if not path.is_file():
        raise LibraryError(f"missing template {path.relative_to(ROOT)}; run 'bootstrap-templates'")
    return path.read_text(encoding="utf-8")


def bootstrap_templates():
    """One-time: derive language shells from the current localized blog hubs (header, footer, head assets)."""
    TEMPLATES.mkdir(parents=True, exist_ok=True)
    for lang in LANGS:
        page = (ROOT / PREFIX[lang] / "blog/index.html").read_text(encoding="utf-8")
        region = re.search(r"<title>.*?</script>\n", page, re.S)
        kept = [l for l in region.group(0).splitlines() if re.match(r'<link rel="(?:stylesheet|icon|apple-touch-icon)"', l)]
        page = page[:region.start()] + "{{HEAD_META}}\n" + "\n".join(kept) + "\n{{HEAD_SOCIAL}}\n" + page[region.end():]
        page = re.sub(r'<style>\.news-grid.*?</style><style>\.blog-card \.guide-thumb.*?</style>', "", page, count=1, flags=re.S)
        page = re.sub(r'(<link rel="stylesheet" href="/assets/blog/newsroom\.css\?v=[a-f0-9]+">)',
                      r'\1\n<link rel="stylesheet" href="/assets/blog/library.css">', page, count=1)
        page = re.sub(r'<main class="page-content newsroom-hub" id="main-content">.*?</main>', "{{MAIN}}", page, count=1, flags=re.S)
        for other in LANGS:
            page = page.replace(f'href="{url(other, "blog/")}" lang=', f'href="{{{{ALT_{other}}}}}" lang=', 1)
        page = page.replace('class="nav-blog-link active" aria-current="page"', 'class="nav-blog-link active"{{BLOG_CURRENT}}', 1)
        if "{{HEAD_META}}" not in page or "{{MAIN}}" not in page or page.count("{{ALT_") != 4:
            raise LibraryError(f"could not derive template for {lang}")
        (TEMPLATES / f"{lang}.html").write_text(page, encoding="utf-8")
    print("templates written to", TEMPLATES.relative_to(ROOT))


def tool_name(lang: str, tool: str) -> str:
    page = (ROOT / PREFIX[lang] / tool / "index.html").read_text(encoding="utf-8")
    h1 = re.search(r"<h1[^>]*>(.*?)</h1>", page, re.S)
    name = unescape(re.sub(r"<[^>]+>", "", h1.group(1))).strip() if h1 else tool
    name = re.split(r"\s+[–—-]\s+|\s*[–—]\s*", name)[0]
    name = re.sub(r"\s+(?:Online|online|en línea|أونلاين|عبر الإنترنت)$", "", name)
    return re.sub(r"\s+", " ", name)


