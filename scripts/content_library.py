def related_for(topic: Topic, published: list[Topic]) -> list[Topic]:
    """Explicit related topics first, then same-category topics published BEFORE this one, then other older topics.
    Using only older topics keeps existing article pages unchanged when new articles are published."""
    by_slug = {t.slug: t for t in published}
    chosen = [by_slug[s] for s in topic.related if s in by_slug and s != topic.slug]
    older = sorted((t for t in published if t.sort_key < topic.sort_key), key=lambda t: t.sort_key, reverse=True)
    newer = sorted((t for t in published if t.sort_key > topic.sort_key), key=lambda t: t.sort_key)
    for pool in ([t for t in older if t.category == topic.category], older, [t for t in newer if t.category == topic.category], newer):
        for t in pool:
            if len(chosen) >= 3:
                break
            if t not in chosen and t is not topic:
                chosen.append(t)
    return chosen[:3]


