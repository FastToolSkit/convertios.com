class LibraryError(ValueError):
    pass


@dataclass
class Version:
    lang: str
    title: str
    description: str
    dek: str
    body: str
    seo_title: str = ""
    cover_alt: str = ""
    html: str = ""
    toc: list = field(default_factory=list)
    words: int = 0


@dataclass
class Topic:
    slug: str
    category: str
    type: str
    published: date
    order: int
    status: str
    cover: str
    tools: list
    related: list
    meta: dict
    sources: list
    versions: dict
    path: Path

    @property
    def sort_key(self):
        return (self.published, self.order, self.slug)


# ---------------------------------------------------------------- parsing

def parse_fields(block: str, where: str) -> tuple[dict, list]:
    fields, sources = {}, []
    for raw in block.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise LibraryError(f"{where}: expected 'key: value' but found {line[:60]!r}")
        key, value = line.split(":", 1)
        key, value = key.strip(), value.strip()
        if key == "source":
            parts = [p.strip() for p in value.split("|")]
            if len(parts) < 2 or not parts[1].startswith("https://"):
                raise LibraryError(f"{where}: source must be 'Title | https://url | optional date'")
            sources.append({"title": parts[0], "url": parts[1], "date": parts[2] if len(parts) > 2 else ""})
        else:
            if key in fields:
                raise LibraryError(f"{where}: duplicate field {key}")
            fields[key] = value
    return fields, sources


def split_list(value: str) -> list:
    return [v.strip() for v in value.split(",") if v.strip()]


def load_topic(path: Path) -> Topic:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    slug = path.stem
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise LibraryError(f"{path.name}: invalid slug")
    m = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not m:
        raise LibraryError(f"{slug}: missing topic front matter")
    meta, sources = parse_fields(m.group(1), slug)
    for key in ("category", "type", "published", "order", "status", "cover"):
        if key not in meta:
            raise LibraryError(f"{slug}: missing {key}")
    if meta["category"] not in CATEGORIES:
        raise LibraryError(f"{slug}: unknown category {meta['category']}")
    if meta["type"] not in TYPES:
        raise LibraryError(f"{slug}: unknown type {meta['type']}")
    if meta["status"] not in STATUSES:
        raise LibraryError(f"{slug}: unknown status {meta['status']}")
    try:
        published = date.fromisoformat(meta["published"])
    except ValueError as exc:
        raise LibraryError(f"{slug}: invalid published date") from exc
    if meta["type"] == "news" and not sources:
        raise LibraryError(f"{slug}: news needs at least one source line")
    versions = {}
    chunks = re.split(r"^=== ([a-z-]+) ===\n", m.group(2), flags=re.M)
    if chunks[0].strip():
        raise LibraryError(f"{slug}: text before the first language block")
    for lang, chunk in zip(chunks[1::2], chunks[2::2]):
        if lang not in LANGS or lang in versions:
            raise LibraryError(f"{slug}: unknown or repeated language block {lang}")
        head, sep, body = chunk.partition("\n---\n")
        if not sep:
            raise LibraryError(f"{slug}/{lang}: missing '---' between fields and body")
        fields, _ = parse_fields(head, f"{slug}/{lang}")
        for key in ("title", "description", "dek"):
            if not fields.get(key):
                raise LibraryError(f"{slug}/{lang}: missing {key}")
        versions[lang] = Version(lang, fields["title"], fields["description"], fields["dek"], body.strip(),
                                 fields.get("seo_title", ""), fields.get("cover_alt", ""))
    return Topic(slug, meta["category"], meta["type"], published, int(meta["order"]), meta["status"], meta["cover"],
                 split_list(meta.get("tools", "")), split_list(meta.get("related", "")), meta, sources, versions, path)


def load_topics() -> list[Topic]:
    topics = [load_topic(p) for p in sorted(CONTENT.glob("*.md"))]
    return topics


# ---------------------------------------------------------------- markdown subset

def url(lang: str, rel: str = "") -> str:
    return f"{BASE}/{PREFIX[lang]}{rel}"


def local(lang: str, rel: str = "") -> str:
    return f"/{PREFIX[lang]}{rel}"


class Renderer:
    def __init__(self, lang: str, slugs: set, where: str):
        self.lang, self.slugs, self.where = lang, slugs, where
        self.internal_blog_links = set()

    def link(self, target: str) -> str:
        if target.startswith("tool:"):
            tool = target[5:]
            if not (ROOT / PREFIX[self.lang] / tool / "index.html").is_file():
                raise LibraryError(f"{self.where}: tool page missing for {target}")
            return local(self.lang, f"{tool}/")
        if target.startswith("blog:"):
            slug, _, anchor = target[5:].partition("#")
            if slug not in self.slugs:
                raise LibraryError(f"{self.where}: link to unpublished or unknown article {slug}")
            self.internal_blog_links.add(slug)
            return local(self.lang, f"blog/{slug}/") + (f"#{anchor}" if anchor else "")
        if target.startswith("https://"):
            return target
        raise LibraryError(f"{self.where}: unsupported link target {target[:80]}")

    def inline(self, text: str) -> str:
        out, pos = [], 0
        pattern = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)|\*\*([^*]+)\*\*|`([^`]+)`")
        for m in pattern.finditer(text):
            out.append(escape(text[pos:m.start()], quote=False))
            if m.group(1) is not None:
                href = self.link(m.group(2))
                ext = ' rel="noopener noreferrer"' if href.startswith("https://") else ""
                out.append(f'<a href="{escape(href)}"{ext}>{self.inline(m.group(1))}</a>')
            elif m.group(3) is not None:
                out.append(f"<strong>{self.inline(m.group(3))}</strong>")
            else:
                out.append(f"<code>{escape(m.group(4), quote=False)}</code>")
            pos = m.end()
        out.append(escape(text[pos:], quote=False))
        return "".join(out)

    def render(self, body: str) -> tuple[str, list]:
        lines = body.split("\n")
        html, toc, para, i = [], [], [], 0
        section_open = False

        def flush():
            if para:
                html.append(f"<p>{self.inline(' '.join(para))}</p>")
                para.clear()

        while i < len(lines):
            line = lines[i].rstrip()
            stripped = line.strip()
            if not stripped:
                flush(); i += 1; continue
            if stripped.startswith("<"):  # trusted raw HTML block (imported legacy copy)
                flush()
                block = []
                while i < len(lines) and lines[i].strip():
                    block.append(lines[i]); i += 1
                html.append("\n".join(block))
                continue
            if stripped.startswith("## "):
                flush()
                if section_open:
                    html.append("</section>")
                anchor = f"s{len(toc) + 1}"
                toc.append((anchor, stripped[3:].strip()))
                html.append(f'<section aria-labelledby="{anchor}"><h2 id="{anchor}">{self.inline(stripped[3:].strip())}</h2>')
                section_open = True
                i += 1; continue
            if stripped.startswith("### "):
                flush(); html.append(f"<h3>{self.inline(stripped[4:].strip())}</h3>"); i += 1; continue
            if stripped.startswith("> "):
                flush()
                quote = []
                while i < len(lines) and lines[i].strip().startswith("> "):
                    quote.append(lines[i].strip()[2:]); i += 1
                html.append(f'<div class="lib-note"><p>{self.inline(" ".join(quote))}</p></div>')
                continue
            if re.match(r"^(- |\d+\. )", stripped):
                flush()
                ordered = bool(re.match(r"^\d+\. ", stripped))
                items = []  # (text, [sub-items])
                while i < len(lines) and re.match(r"^(- |\d+\. )", lines[i].strip()):
                    raw = lines[i]
                    text = re.sub(r"^(- |\d+\. )", "", raw.strip())
                    if raw.startswith("  ") and items:
                        items[-1][1].append(text)
                    else:
                        items.append((text, []))
                    i += 1
                tag = "ol" if ordered else "ul"
                html.append(f"<{tag}>" + "".join(
                    f"<li>{self.inline(x)}" + (("<ul>" + "".join(f"<li>{self.inline(y)}</li>" for y in sub) + "</ul>") if sub else "") + "</li>"
                    for x, sub in items) + f"</{tag}>")
                continue
            if stripped.startswith("|"):
                flush()
                rows = []
                while i < len(lines) and lines[i].strip().startswith("|"):
                    rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")]); i += 1
                if len(rows) < 3 or not all(re.fullmatch(r":?-{3,}:?", c) for c in rows[1]):
                    raise LibraryError(f"{self.where}: malformed table")
                head = "".join(f'<th scope="col">{self.inline(c)}</th>' for c in rows[0])
                body_rows = "".join("<tr>" + "".join((f'<th scope="row">{self.inline(c)}</th>' if j == 0 else f"<td>{self.inline(c)}</td>") for j, c in enumerate(r)) + "</tr>" for r in rows[2:])
                html.append(f'<div class="lib-table" tabindex="0" role="region" aria-label="{escape(rows[0][0])}"><table><thead><tr>{head}</tr></thead><tbody>{body_rows}</tbody></table></div>')
                continue
            para.append(stripped)
            i += 1
        flush()
        if section_open:
            html.append("</section>")
        return "\n".join(html), toc


def word_count(html: str) -> int:
    text = unescape(re.sub(r"<[^>]+>", " ", html))
    return len(re.findall(r"\w+", text))


